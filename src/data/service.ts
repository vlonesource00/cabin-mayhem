import { z } from 'zod';

const pointSchema = z.object({ x: z.number().finite(), y: z.number().finite() });
const serviceNeedSchema = z.enum(['drink', 'meal', 'medical']);

export const passengerDefinitionSchema = z.object({
  id: z.string().regex(/^passenger-[a-z0-9-]+$/),
  name: z.string().min(1),
  seatPosition: pointSchema,
  servicePosition: pointSchema,
  color: z.string().regex(/^#[0-9a-f]{6}$/i),
  need: serviceNeedSchema,
  requestAt: z.number().min(0).max(600),
});

export const serviceObjectDefinitionSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string().min(1),
  kind: z.enum(['drink', 'meal-tray', 'medkit', 'extinguisher']),
  material: z.enum(['metal', 'plastic', 'cargo']),
  position: pointSchema,
  radius: z.number().positive().max(1),
  mass: z.number().positive().max(25),
  friction: z.number().min(0).max(1),
  impactTolerance: z.number().positive(),
  secured: z.boolean(),
  serviceNeed: serviceNeedSchema.optional(),
});

export const serviceSliceDefinitionSchema = z.object({
  duration: z.number().min(60).max(1800),
  passengers: z.array(passengerDefinitionSchema).min(8).max(12),
  objects: z.array(serviceObjectDefinitionSchema).min(7),
});

export type PassengerDefinition = z.infer<typeof passengerDefinitionSchema>;
export type ServiceObjectDefinition = z.infer<typeof serviceObjectDefinitionSchema>;

